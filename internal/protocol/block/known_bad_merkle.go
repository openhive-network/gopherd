// MerkleRootAccepted reports whether merkle is acceptable for blockNum:
// either it equals the header's stored root (handled by the caller), or it
// matches the algorithmically-correct value the network has accepted as
// an exception for that specific block.
func MerkleRootAccepted(blockNum uint32, merkle [20]byte, headerRoot [20]byte) bool {
	if merkle == headerRoot {
		return true
	}
	known, ok := KnownBadMerkleRoots[blockNum]
	return ok && merkle == known
}
