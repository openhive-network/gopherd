// Command testnet-config emits per-node config.ini directories for a
// ghive testnet deployment.
//
// Usage:
//
//	testnet-config -N=5 -out-dir=./testnet/
//
// Produces ./testnet/node-1/, ./testnet/node-2/, ... each with a
// config.ini wired up to:
//
//   - data-dir = ./data
//   - p2p-endpoint = 127.0.0.1:(9876 + i-1)
//   - p2p-seed-node entries pointing at every OTHER node
//   - witness = <round-robin-assigned init-N witnesses>
//   - private-key = <matching WIFs>
//
// The 21 init witnesses are assigned across N nodes round-robin; if N
// doesn't divide 21 evenly the first (21 % N) nodes own one extra
// witness. With N=5: nodes 1 own 5, nodes 2-5 own 4 each.
//
// Per-node config.ini also pre-loads the matching node-operator WIF
// (so the operator can post / vote / transfer from the node it runs).
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"hived-go/internal/state/genesis"
)

const (
	defaultBaseP2PPort = 9876
	defaultBaseRPCPort = 8090
)

func main() {
	var (
		nodeCount   int
		outDir      string
		baseP2PPort int
		baseRPCPort int
		listenIP    string
	)
	flag.IntVar(&nodeCount, "N", genesis.DefaultTestnetOperatorCount,
		"number of nodes (each gets 1 operator account + ~21/N witnesses)")
	flag.StringVar(&outDir, "out-dir", "./testnet",
		"directory to write per-node config.ini trees into")
	flag.IntVar(&baseP2PPort, "p2p-base", defaultBaseP2PPort,
		"first p2p port; node-i listens on (p2p-base + i - 1)")
	flag.IntVar(&baseRPCPort, "rpc-base", defaultBaseRPCPort,
		"first webserver-http-endpoint port (0 = disable RPC)")
	flag.StringVar(&listenIP, "listen-ip", "127.0.0.1",
		"interface to bind p2p-endpoint and rpc-endpoint to")
	flag.Parse()

	if nodeCount < 1 || nodeCount > 64 {
		fmt.Fprintf(os.Stderr, "testnet-config: N must be in [1,64], got %d\n", nodeCount)
		os.Exit(2)
	}
	if nodeCount > genesis.TestnetWitnessCount {
		fmt.Fprintf(os.Stderr,
			"testnet-config: N=%d exceeds TestnetWitnessCount=%d (would leave nodes with no witnesses)\n",
			nodeCount, genesis.TestnetWitnessCount)
		os.Exit(2)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "testnet-config: mkdir %s: %v\n", outDir, err)
		os.Exit(1)
	}

	witnessAssignment := assignWitnesses(nodeCount, genesis.TestnetWitnessCount)
	witnessKeys := genesis.TestnetWitnessKeys()
	operatorKeys := genesis.TestnetOperatorKeys(nodeCount)

	for i := 0; i < nodeCount; i++ {
		nodeDir := filepath.Join(outDir, fmt.Sprintf("node-%d", i+1))
		dataDir := filepath.Join(nodeDir, "data")
		if err := os.MkdirAll(dataDir, 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "testnet-config: mkdir %s: %v\n", dataDir, err)
			os.Exit(1)
		}

		ourPort := baseP2PPort + i
		var seedEndpoints []string
		for j := 0; j < nodeCount; j++ {
			if j == i {
				continue
			}
			seedEndpoints = append(seedEndpoints, fmt.Sprintf("%s:%d", listenIP, baseP2PPort+j))
		}

		var sb strings.Builder
		fmt.Fprintf(&sb, "# ghive testnet config — node-%d of %d\n", i+1, nodeCount)
		fmt.Fprintf(&sb, "# Generated by cmd/testnet-config; safe to edit by hand.\n\n")
		fmt.Fprintf(&sb, "data-dir = data\n")
		fmt.Fprintf(&sb, "p2p-endpoint = %s:%d\n", listenIP, ourPort)
		if baseRPCPort > 0 {
			fmt.Fprintf(&sb, "webserver-http-endpoint = %s:%d\n", listenIP, baseRPCPort+i)
		}
		for _, sd := range seedEndpoints {
			fmt.Fprintf(&sb, "p2p-seed-node = %s\n", sd)
		}
		sb.WriteString("\n# Witness producers owned by this node (round-robin from genesis init witnesses).\n")
		for _, widx := range witnessAssignment[i] {
			w := witnessKeys[widx]
			fmt.Fprintf(&sb, "witness = \"%s\"\n", w.Name)
			fmt.Fprintf(&sb, "private-key = %s\n", w.WIF)
		}
		// Node-operator key is emitted only as a comment so the active
		// `private-key` count matches `witness` count (the config
		// parser asserts these are equal). Tooling can re-read the
		// operator WIF via genesis.TestnetOperatorKeys(N) when it
		// needs to drive transactions on behalf of this node's
		// operator account.
		sb.WriteString("\n# Node-operator (this node's funded account; NOT a witness).\n")
		op := operatorKeys[i]
		fmt.Fprintf(&sb, "# operator-account = %s\n", op.Name)
		fmt.Fprintf(&sb, "# operator-private-key = %s\n", op.WIF)

		cfgPath := filepath.Join(nodeDir, "config.ini")
		if err := os.WriteFile(cfgPath, []byte(sb.String()), 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "testnet-config: write %s: %v\n", cfgPath, err)
			os.Exit(1)
		}
		fmt.Printf("wrote %s (%d witnesses, p2p=%s:%d)\n",
			cfgPath, len(witnessAssignment[i]), listenIP, ourPort)
	}
}

// assignWitnesses round-robins witnessCount witnesses across nodeCount
// nodes. Returns a [nodeCount][]witnessIndex slice. Witness index 0
// → init-1, etc.
//
// Round-robin ensures the schedule cycles ACROSS nodes (block 1 = node 1,
// block 2 = node 2, ...) instead of running blocks of consecutive
// witnesses on the same node — which is what we want for a real
// distributed-fault-tolerance test.
func assignWitnesses(nodeCount, witnessCount int) [][]int {
	out := make([][]int, nodeCount)
	for i := 0; i < witnessCount; i++ {
		node := i % nodeCount
		out[node] = append(out[node], i)
	}
	return out
}
