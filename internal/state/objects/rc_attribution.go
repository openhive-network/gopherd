// Call-site attribution for the last_max_rc staleness counter.
//
// A bare count answers "how often" and nothing else. 28 million hits across a
// genesis→35.93M replay is either a bug in gopherd's RC bookkeeping or a
// difference in ORDER — hived's convention is regenerate-then-mutate, and its
// paired assertion ("not regenerated prior to VEST change") exists precisely
// because the other order leaves the cache stale through no fault of the
// arithmetic. Those two readings call for opposite work, and the count cannot
// tell them apart.
//
// What distinguishes them is WHERE the stale read happens. A site that mutates
// vesting and then regenerates is an ordering artifact: hived would have
// regenerated first and seen a fresh cache. A site that only reads — a
// transaction paying RC, say — has no business finding the cache stale at all,
// and a hit there means some earlier operation failed to maintain it.
//
// So record the caller. Enabled by GOPHERD_RC_ATTRIBUTION=1 because the
// condition fires ~2.5 times per block: runtime.Caller on that path is fine
// for a diagnostic run and not fine for every replay.
var rcAttributionEnabled = os.Getenv("GOPHERD_RC_ATTRIBUTION") != ""

// RCAttributionEnabled reports whether call-site attribution is recording.
func RCAttributionEnabled() bool { return rcAttributionEnabled }

// rcCallers maps a caller PC to its hit count. Keyed on the raw PC so the hot
// path does no symbol lookup; names are resolved once, at reporting time.
var rcCallers sync.Map // uintptr -> *atomic.Uint64

// noteRCStaleCaller records one stale-cache hit against its immediate caller.
// skip is the number of frames between here and the site of interest.
func noteRCStaleCaller(skip int) {
	pc, _, _, ok := runtime.Caller(skip)
	if !ok {
		return
	}
	if v, hit := rcCallers.Load(pc); hit {
		v.(*atomic.Uint64).Add(1)
		return
	}
	c := &atomic.Uint64{}
	c.Add(1)
	if actual, loaded := rcCallers.LoadOrStore(pc, c); loaded {
		actual.(*atomic.Uint64).Add(1)
	}
}

// rcNotRegenCallers is the same attribution for the OTHER condition — a
// post-change refresh arriving without a prior regeneration this block. Kept
// separate because the two conditions call for different fixes: a stale max
// means the cache disagrees with its reader, while a missing regeneration
// means the call ORDER differs from hived's.
var rcNotRegenCallers sync.Map // uintptr -> *atomic.Uint64

func noteRCNotRegenCaller(skip int) {
	pc, _, _, ok := runtime.Caller(skip)
	if !ok {
		return
	}
	if v, hit := rcNotRegenCallers.Load(pc); hit {
		v.(*atomic.Uint64).Add(1)
		return
	}
	c := &atomic.Uint64{}
	c.Add(1)
	if actual, loaded := rcNotRegenCallers.LoadOrStore(pc, c); loaded {
		actual.(*atomic.Uint64).Add(1)
	}
}

// RCStaleCallSite is one attributed call site.
type RCStaleCallSite struct {
	Func  string
	File  string
	Line  int
	Count uint64
}

// RCStaleCallSites resolves the recorded PCs to source locations, busiest
// first. Empty unless GOPHERD_RC_ATTRIBUTION was set.
func RCStaleCallSites() []RCStaleCallSite { return resolveSites(&rcCallers) }

// RCNotRegenCallSites is the same for the missing-regeneration condition.
func RCNotRegenCallSites() []RCStaleCallSite { return resolveSites(&rcNotRegenCallers) }

func resolveSites(m *sync.Map) []RCStaleCallSite {
	var out []RCStaleCallSite
	m.Range(func(k, v any) bool {
		pc := k.(uintptr)
		n := v.(*atomic.Uint64).Load()
		site := RCStaleCallSite{Count: n, Func: "?"}
		// CallersFrames wants the return address, which is what runtime.Caller
		// hands back; it adjusts internally. Using FuncForPC directly here
		// would attribute inlined frames to their parent.
		frames := runtime.CallersFrames([]uintptr{pc})
		if f, _ := frames.Next(); f.Function != "" {
			site.Func = shortFuncName(f.Function)
			site.File = shortFile(f.File)
			site.Line = f.Line
		}
		out = append(out, site)
		return true
	})
	sort.Slice(out, func(i, j int) bool { return out[i].Count > out[j].Count })
	return out
}

// FormatRCStaleCallSites renders the attribution table for a replay summary.
// Returns "" when nothing was recorded, so callers can skip the section.
func FormatRCStaleCallSites(limit int) string {
	return formatSites("rc stale max by call site", RCStaleCallSites(), limit)
}

// FormatRCNotRegenCallSites is the same for the missing-regeneration counter.
func FormatRCNotRegenCallSites(limit int) string {
	return formatSites("rc not-regenerated by call site", RCNotRegenCallSites(), limit)
}

func formatSites(label string, sites []RCStaleCallSite, limit int) string {
	if len(sites) == 0 {
		return ""
	}
	var total uint64
	for _, s := range sites {
		total += s.Count
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s (%d distinct, %d hits):\n", label, len(sites), total)
	for i, s := range sites {
		if limit > 0 && i >= limit {
			fmt.Fprintf(&b, "  ... %d more sites\n", len(sites)-i)
			break
		}
		pct := float64(s.Count) / float64(total) * 100
		fmt.Fprintf(&b, "  %8d  %5.1f%%  %s  (%s:%d)\n", s.Count, pct, s.Func, s.File, s.Line)
	}
	return b.String()
}

// shortFuncName strips the module path, leaving package.Func.
func shortFuncName(full string) string {
	if i := strings.LastIndex(full, "/"); i >= 0 {
		return full[i+1:]
	}
	return full
}

// shortFile keeps the last two path segments — enough to identify the file
// without the build machine's directory layout.
func shortFile(full string) string {
	parts := strings.Split(full, "/")
	if len(parts) <= 2 {
		return full
	}
	return strings.Join(parts[len(parts)-2:], "/")
}
